import { SwrServiceWorkerConfig } from './types';

export const DEFAULT_BYPASS_PATH_PREFIXES = ['/api/'] as const;

export const DEFAULT_BYPASS_HOSTNAMES = [
  'googleapis.com',
  'google-analytics',
  'googletagmanager.com',
  'clarity.ms',
  'sentry.io',
] as const;

export const DEFAULT_IMMUTABLE_CHUNK_PREFIXES = [
  '/_next/static/',
  '/assets/',
] as const;

const STATIC_ASSET_EXT_REGEX =
  /\.(?:png|jpg|jpeg|svg|webp|gif|ico|woff|woff2|ttf|otf|css|js|mjs)(?:\?.*)?$/i;

const STATIC_DESTINATIONS = new Set(['style', 'script', 'image', 'font']);

/**
 * Detects API routes (`/api/`), Next.js RSC payloads (`_rsc`, `rsc: 1`,
 * `next-router-prefetch: 1`, `Accept: text/x-component`), and analytics/telemetry
 * domains that must NEVER be cached or intercepted by a Service Worker.
 */
export function isApiOrRscRequest(
  url: URL | string,
  headers?: Record<string, string | undefined> | Headers,
  options?: {
    bypassPathPrefixes?: readonly string[];
    bypassHostnames?: readonly string[];
  }
): boolean {
  const parsedUrl = typeof url === 'string' ? new URL(url, 'https://localhost') : url;

  if (parsedUrl.searchParams.has('_rsc')) {
    return true;
  }

  const getHeader = (name: string): string | undefined => {
    if (!headers) return undefined;
    if (typeof (headers as Headers).get === 'function') {
      return (headers as Headers).get(name) ?? undefined;
    }
    const record = headers as Record<string, string | undefined>;
    const lower = name.toLowerCase();
    for (const key of Object.keys(record)) {
      if (key.toLowerCase() === lower) {
        return record[key];
      }
    }
    return undefined;
  };

  if (
    getHeader('rsc') === '1' ||
    getHeader('next-router-prefetch') === '1' ||
    (getHeader('accept') ?? '').includes('text/x-component')
  ) {
    return true;
  }

  const pathPrefixes = options?.bypassPathPrefixes ?? DEFAULT_BYPASS_PATH_PREFIXES;
  for (const prefix of pathPrefixes) {
    if (parsedUrl.pathname.startsWith(prefix)) {
      return true;
    }
  }

  const hostnames = options?.bypassHostnames ?? DEFAULT_BYPASS_HOSTNAMES;
  const hostname = parsedUrl.hostname.toLowerCase();
  for (const pattern of hostnames) {
    if (hostname.includes(pattern.toLowerCase())) {
      return true;
    }
  }

  return false;
}

/**
 * Detects immutable hashed static chunks (`/_next/static/`, `/assets/`) or
 * static asset files (`.js`, `.css`, `.woff2`, `.webp`, etc.).
 */
export function isStaticChunkAsset(
  pathname: string,
  destination?: string
): boolean {
  if (destination && STATIC_DESTINATIONS.has(destination)) {
    return true;
  }
  for (const prefix of DEFAULT_IMMUTABLE_CHUNK_PREFIXES) {
    if (pathname.startsWith(prefix)) {
      return true;
    }
  }
  return STATIC_ASSET_EXT_REGEX.test(pathname);
}

/**
 * Detects when an immutable hashed JS/CSS chunk returns `HTTP 404` after a new
 * deployment so the Service Worker immediately purges stale HTML navigation
 * shells from Cache Storage (Self-Healing 404 Chunk Guard).
 */
export function shouldTrigger404SelfHeal(
  status: number,
  pathname: string,
  chunkPrefixes: readonly string[] = DEFAULT_IMMUTABLE_CHUNK_PREFIXES
): boolean {
  if (status !== 404) {
    return false;
  }
  return chunkPrefixes.some((prefix) => pathname.startsWith(prefix));
}

/**
 * Generates a complete, production-ready `sw.js` script implementing:
 * - Core asset precaching + immediate `skipWaiting()`
 * - `navigationPreload` enablement + outdated cache eviction + `clients.claim()`
 * - Non-blocking Warm Shell Prefetch on activation
 * - Strategy 0: Network-only bypass for API routes, Next.js RSC payloads, and telemetry
 * - Strategy 1: Stale-While-Revalidate (SWR) for HTML navigation (`<10ms TTFB`) + Offline fallback
 * - Strategy 2: Cache-First static assets + 404 Chunk Self-Healing HTML shell purge
 */
export function generateSwrServiceWorkerCode(
  config: SwrServiceWorkerConfig
): string {
  const cacheName = config.cacheName;
  const offlineFallbackUrl = config.offlineFallbackUrl ?? '/offline.html';
  const precacheAssets = config.precacheAssets ?? [offlineFallbackUrl];
  const warmShellRoutes = config.warmShellRoutes ?? [];
  const canonicalPathPrefixes = config.canonicalPathPrefixes ?? [];
  const immutableChunkPrefixes =
    config.immutableChunkPrefixes ?? [...DEFAULT_IMMUTABLE_CHUNK_PREFIXES];
  const bypassPathPrefixes =
    config.bypassPathPrefixes ?? [...DEFAULT_BYPASS_PATH_PREFIXES];
  const bypassHostnames =
    config.bypassHostnames ?? [...DEFAULT_BYPASS_HOSTNAMES];
  const enableNavigationPreload = config.enableNavigationPreload ?? true;

  return `// Generated by @kido/pwa-swr-guard
const CACHE_NAME = ${JSON.stringify(cacheName)};
const OFFLINE_FALLBACK = ${JSON.stringify(offlineFallbackUrl)};
const PRECACHE_ASSETS = ${JSON.stringify(precacheAssets, null, 2)};
const WARM_SHELL_ROUTES = ${JSON.stringify(warmShellRoutes)};
const CANONICAL_PATH_PREFIXES = ${JSON.stringify(canonicalPathPrefixes)};
const IMMUTABLE_CHUNK_PREFIXES = ${JSON.stringify(immutableChunkPrefixes)};
const BYPASS_PATH_PREFIXES = ${JSON.stringify(bypassPathPrefixes)};
const BYPASS_HOSTNAMES = ${JSON.stringify(bypassHostnames)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(PRECACHE_ASSETS);
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      if (${enableNavigationPreload ? 'self.registration.navigationPreload' : 'false'}) {
        try {
          await self.registration.navigationPreload.enable();
        } catch (e) {
          console.warn('[SW] Navigation preload enable failed:', e);
        }
      }

      const keys = await caches.keys();
      await Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      );
      await self.clients.claim();

      if (WARM_SHELL_ROUTES.length > 0) {
        caches.open(CACHE_NAME).then((c) => {
          WARM_SHELL_ROUTES.forEach((p) => {
            fetch(p)
              .then((r) => {
                if (isHtmlResponse(r)) c.put(self.location.origin + p, r);
              })
              .catch(() => {});
          });
        });
      }
    })()
  );
});

function isApiOrRscRequest(url, request) {
  if (
    url.searchParams.has('_rsc') ||
    request.headers.get('rsc') === '1' ||
    request.headers.get('next-router-prefetch') === '1' ||
    (request.headers.get('accept') || '').includes('text/x-component')
  ) {
    return true;
  }
  if (BYPASS_PATH_PREFIXES.some((prefix) => url.pathname.startsWith(prefix))) {
    return true;
  }
  const hostname = url.hostname.toLowerCase();
  return BYPASS_HOSTNAMES.some((h) => hostname.includes(h.toLowerCase()));
}

function isImmutableChunk(pathname) {
  return IMMUTABLE_CHUNK_PREFIXES.some((prefix) => pathname.startsWith(prefix));
}

function isStaticAsset(url, request) {
  const destination = request.destination;
  if (['style', 'script', 'image', 'font'].includes(destination)) {
    return true;
  }
  if (isImmutableChunk(url.pathname)) {
    return true;
  }
  return /\\.(?:png|jpg|jpeg|svg|webp|gif|ico|woff|woff2|ttf|otf|css|js|mjs)(?:\\?.*)?$/i.test(url.pathname);
}

function isHtmlResponse(response) {
  if (!response || response.status !== 200) return false;
  const contentType = response.headers.get('content-type') || '';
  return contentType.includes('text/html');
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (!url.protocol.startsWith('http')) return;

  // Strategy 0: Bypass API, Next.js RSC payloads, and external telemetry
  if (isApiOrRscRequest(url, request)) {
    return;
  }

  // Strategy 1: HTML Navigation Stale-While-Revalidate (SWR) for <10ms TTFB
  if (request.mode === 'navigate' || (request.headers.get('accept') || '').includes('text/html')) {
    event.respondWith(
      (async () => {
        const isCanonicalRoute = CANONICAL_PATH_PREFIXES.some((prefix) =>
          url.pathname.startsWith(prefix)
        );
        const canonicalUrl = isCanonicalRoute
          ? \`\${url.origin}\${url.pathname}\`
          : request.url;
        const cache = await caches.open(CACHE_NAME);
        const cachedResponse =
          (await cache.match(canonicalUrl)) || (await cache.match(request));

        const revalidateFromNetwork = async () => {
          try {
            const preloadResponse = await event.preloadResponse;
            if (preloadResponse && isHtmlResponse(preloadResponse)) {
              await cache.put(canonicalUrl, preloadResponse.clone());
              return preloadResponse;
            }
            const networkResponse = await fetch(request);
            if (isHtmlResponse(networkResponse)) {
              await cache.put(canonicalUrl, networkResponse.clone());
            }
            return networkResponse;
          } catch (err) {
            return null;
          }
        };

        if (cachedResponse && isHtmlResponse(cachedResponse)) {
          event.waitUntil(revalidateFromNetwork());
          return cachedResponse;
        }

        const freshResponse = await revalidateFromNetwork();
        if (freshResponse) return freshResponse;

        const offlineResponse = await cache.match(OFFLINE_FALLBACK);
        if (offlineResponse) return offlineResponse;

        return new Response('Offline: Service Unavailable', {
          status: 503,
          statusText: 'Service Unavailable',
          headers: { 'Content-Type': 'text/plain; charset=utf-8' },
        });
      })()
    );
    return;
  }

  // Strategy 2: Static assets -> Cache-First + 404 Chunk Self-Healing Guard
  if (isStaticAsset(url, request)) {
    event.respondWith(
      caches.match(request).then((cachedResponse) => {
        if (cachedResponse) {
          if (url.origin === self.location.origin && !isImmutableChunk(url.pathname)) {
            fetch(request)
              .then((networkResponse) => {
                if (networkResponse && networkResponse.status === 200) {
                  caches.open(CACHE_NAME).then((cache) => cache.put(request, networkResponse));
                }
              })
              .catch(() => {});
          }
          return cachedResponse;
        }

        return fetch(request).then((networkResponse) => {
          if (networkResponse && networkResponse.status === 404 && isImmutableChunk(url.pathname)) {
            // Self-Healing 404 Chunk Guard: evict cached HTML navigation shells
            caches.open(CACHE_NAME).then(async (cache) => {
              const reqs = await cache.keys();
              await Promise.all(
                reqs.map((r) => (!isStaticAsset(new URL(r.url), r) ? cache.delete(r) : null))
              );
            });
            return networkResponse;
          }

          if (networkResponse && (networkResponse.status === 200 || networkResponse.type === 'opaque')) {
            const responseClone = networkResponse.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, responseClone));
          }
          return networkResponse;
        });
      })
    );
    return;
  }

  // Strategy 3: Default Network-First with cache fallback
  event.respondWith(
    fetch(request).catch(() => caches.match(request))
  );
});
`;
}
