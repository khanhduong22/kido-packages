import type { HeaderCollection } from './types';

/**
 * Extract a header value case-insensitively from various header representations
 * (Web standard Headers, Node.js IncomingHttpHeaders record, or Map).
 */
export function getHeaderValue(headers: HeaderCollection | null | undefined, name: string): string | null {
  if (!headers) return null;

  const targetName = name.toLowerCase();

  // If Map instance (Map.get is case-sensitive, so check entries case-insensitively)
  if (headers instanceof Map) {
    for (const [key, value] of headers.entries()) {
      if (key.toLowerCase() === targetName) {
        return typeof value === 'string' ? value : String(value);
      }
    }
    return null;
  }

  // If Web Standard Headers instance (Headers.get is case-insensitive by W3C Fetch spec)
  if (typeof (headers as Headers).get === 'function') {
    return (headers as Headers).get(targetName);
  }

  // Standard Record<string, string | string[] | undefined>
  if (typeof headers === 'object') {
    for (const key of Object.keys(headers)) {
      if (key.toLowerCase() === targetName) {
        const val = (headers as Record<string, string | string[] | undefined>)[key];
        if (Array.isArray(val)) {
          return val.join(', ');
        }
        return val ? String(val) : null;
      }
    }
  }

  return null;
}

/**
 * Checks if the request was generated by a speculative prefetch, prerender,
 * or background preview from browsers (Chrome, Firefox, Safari, Edge).
 *
 * Prevents false-positive pageviews, ad click inflations, and premature session creation.
 */
export function isSpeculativePrefetch(headers: HeaderCollection | null | undefined): boolean {
  if (!headers) return false;

  // 1. W3C Resource Hints / Sec-Purpose (modern Chromium, Edge, Opera)
  // e.g. "sec-purpose: prefetch" or "sec-purpose: prerender"
  const secPurpose = getHeaderValue(headers, 'sec-purpose');
  if (secPurpose) {
    const val = secPurpose.toLowerCase();
    if (val.includes('prefetch') || val.includes('prerender')) {
      return true;
    }
  }

  // 2. Purpose header (Legacy Chrome, Safari speculative fetch)
  // e.g. "purpose: prefetch"
  const purpose = getHeaderValue(headers, 'purpose');
  if (purpose) {
    const val = purpose.toLowerCase();
    if (val.includes('prefetch') || val.includes('preview')) {
      return true;
    }
  }

  // 3. Firefox speculative link prefetching
  // e.g. "X-Moz: prefetch"
  const xMoz = getHeaderValue(headers, 'x-moz');
  if (xMoz && xMoz.toLowerCase().includes('prefetch')) {
    return true;
  }

  // 4. X-Purpose header (various CDN & mobile in-app webview previews)
  // e.g. "X-Purpose: preview", "X-Purpose: prefetch"
  const xPurpose = getHeaderValue(headers, 'x-purpose');
  if (xPurpose) {
    const val = xPurpose.toLowerCase();
    if (val.includes('preview') || val.includes('prefetch')) {
      return true;
    }
  }

  // 5. X-Prerender (Search engine / browser headless prerender bots)
  const xPrerender = getHeaderValue(headers, 'x-prerender');
  if (xPrerender && (xPrerender === '1' || xPrerender.toLowerCase() === 'true')) {
    return true;
  }

  return false;
}

/**
 * Returns the detected prefetch classification, or null if it's a standard user navigation.
 */
export function getPrefetchType(headers: HeaderCollection | null | undefined): 'prefetch' | 'prerender' | 'preview' | null {
  if (!headers) return null;

  const secPurpose = getHeaderValue(headers, 'sec-purpose')?.toLowerCase();
  if (secPurpose?.includes('prerender')) return 'prerender';
  if (secPurpose?.includes('prefetch')) return 'prefetch';

  const purpose = getHeaderValue(headers, 'purpose')?.toLowerCase();
  if (purpose?.includes('preview')) return 'preview';
  if (purpose?.includes('prefetch')) return 'prefetch';

  const xMoz = getHeaderValue(headers, 'x-moz')?.toLowerCase();
  if (xMoz?.includes('prefetch')) return 'prefetch';

  const xPurpose = getHeaderValue(headers, 'x-purpose')?.toLowerCase();
  if (xPurpose?.includes('preview')) return 'preview';
  if (xPurpose?.includes('prefetch')) return 'prefetch';

  const xPrerender = getHeaderValue(headers, 'x-prerender')?.toLowerCase();
  if (xPrerender === '1' || xPrerender === 'true') return 'prerender';

  return null;
}
